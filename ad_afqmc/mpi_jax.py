comm = MPI.COMM_WORLD
size = comm.Get_size()
rank = comm.Get_rank()

"""
MPI-enabled AFQMC. The entire AFQMC happens in this **standalone script**
- run_afqmc.py is only a even-higher-level convenience script that MPI-calls this script 
- Prepares AFQMC initial state and precontractions
- Finds the right driver to use based on options
    - free_projection        -> driver.afqmcFp
    - do_grad                -> driver.afmqcGrad (a modified variant of the below)
        - uses propagate_phaseless_nucgrad_* wrappers
        - writes stuff to disk, does the additional stuff we do to get nucgrad
    - (nothing)              -> driver.afqmc (standard ph-AFQMC, unfortunately called "afqmc")

The most important thing is the _prep_afqmc(options) function (which is the only one here!)
- ham_data, ham, prop, trial, wave_data, observable, options = _prep_afqmc()
- so this thing creates ALL of the initial stuff needed for an AFQMC computation
- but the only arg is options! so where do the integrals come from:
    - turns out we read from DISK: a **H5** file called `FCIDUMP_chol` with pyscf-intermediates
    - this file is generated by another code in this repo, bc "chol" means it is AFQMC-specific
        - example files show that it comes from pyscf_interface.prep_afqmc(mf)
        - so the full workflow is, mf -> fci -> pyscf_interface.prep_afqmc -> mpi_jax.prep_afqmc
            - wtf...
    - anyways we expect the h0, h1, h2 integrals to be in the dump
    - also expect the N, K, X info of the system to be in the dump's header
        - [nelec, nmo, ms, nchol] = fh5["header"]
        - ms is used to compute nelec alpha and beta for UHF
        - these are later stored into the hamiltonian.hamiltonian object
- next we get the options. again this is crazy
    - Method 1. Directly supply options into _prep_afqmc. No examples of this
    - Method 2. Read a pickle from disk: options.bin
    - Default. Constructs a new options dict on the spot.
        - ALL THE DEFAULT VALUES FOR OPTIONS ARE HARDCODED HERE
- next we read another file from DISK, observable.h5
    - the constant term of the observable op that gets directly added to the exp value
    - an KxK matrix 'op', which is the observable integrals A_mn
        - based on this I think only ONE 1b observable is supported
- now we are ready to form the objects
    - ham_data is a dict containing 2q params h0, h1, chol, + more stuff later
        - h1 also has a corresponding 'mask' stored in ham_data ???
        - ene0 ??? seems to be a weird fp thing, the only place used is in fp
            - examples always set ene0 = 0.0, so what is the point???
            ham_data["h0_prop_fp"] = jnp.stack(
            (
                (ham_data["h0_prop"] + ham_data["ene0"]) / self.nelec[0] / 2.0,
                (ham_data["h0_prop"] + ham_data["ene0"]) / self.nelec[1] / 2.0,
            )
        - dm0 is the dm0 for SCF (init 1rdm) in wavefunctions.*hf.optimize_orbs()
            - basically they wrote a custom HF SCF function there
                - why? isn't the pyscf hf good enough
            - only application is in L242, gets set to Integral_der.npz["dm"]
                - see grad_utils.FD_integrals()
                - basis0 = np.array(fractional_matrix_power(mf.get_ovlp(), -0.5),dtype="float64")
                ... [basis0 is the symmetric (Löwdin) orthogonalizer]
                - dm0 = basis0.T @ mf.get_ovlp() @ mf.make_rdm1()@ mf.get_ovlp() @ basis0
                ... I feel this is redundant, it really is just S1/2 D S1/2
                - np.savez("Integral_der.npz",array1 = h1_der_array,array2=h2_der_array,array3=h0_der,dm=dm0)
            - so dm0 is the density in the orthogonalized AO basis
            - then using this density, we do a custom SCF later on
                - answer: used as initial guess for internal HF-SCF that makes trial depend on integrals
    - creates objects
        - ham = hamiltonian.hamiltonian(the 3 numbers from the fcidump header)
            - ham is mainly here to provide 3 functions, parametrized by the 3 numbers,
            for later transformations of the integrals
        - prop = propagation.propagator(the params for propagation)
            - timestep, num of walkers 
            - steps per energy block, energy blocks per sr block, sr blocks per "block"
                - total time is the product of all four and timestep
        - trial = wavefunctions.rhf(K, N)
            - no actual data are stored in this!
        - to me it looks like ham, prop, trial are all class objects
        that are only collections of functions, param'd by a couple constants
    - loads wave_data as the mo_coeff from a rhf.npz dump
        - for simplicity, ignore UHF, NOCI, for now... they follow a similar structure
        - this is HORRIBLE naming, it is really ambiguous
            - first, we usually don't use our intuitive idea of a wave when we think about wfns
                - we just think about it as a "state", a vector
            - second, the name tells us nothing about which wfn it is referring to
                - who could guess that this refers to the trial specifically??
        - a better name would be trial_wfn (trot makes this change)
- finally dumps K, N, options for debug
- returned stuff: (exactly what driver.afqmc* needs)
    - ham_data, wave_data, observable       tensors
    - ham, prop, trial                      KNX-param'd core functions
    - options                               dict of stuff
- disk files read:
    - FCIDUMP_chol (h5)
    - options.bin (pickle, optional)
    - observable.h5
    - rhf.npz / uhf.npz / dets.pkl
    - Integral_der.npz (do_grad mode only)

NOTE: Here, the integrals h1 and chol are not transformed in any way! They are simply read from the disk.
- This is good for us because it is relatively independent.

Next steps: (1) see how the disk files are made, (2) see how driver works
"""


def _prep_afqmc(options=None):
    if rank == 0:
        print(f"# Number of MPI ranks: {size}\n#")

    with h5py.File("FCIDUMP_chol", "r") as fh5:
        [nelec, nmo, ms, nchol] = fh5["header"]
        h0 = jnp.array(fh5.get("energy_core"))
        h1 = jnp.array(fh5.get("hcore")).reshape(nmo, nmo)
        chol = jnp.array(fh5.get("chol")).reshape(-1, nmo, nmo)

    nelec_sp = ((nelec + abs(ms)) // 2, (nelec - abs(ms)) // 2)

    norb = nmo

    if options is None:
        try:
            with open("options.bin", "rb") as f:
                options = pickle.load(f)
        except:
            options = {}

    options["dt"] = options.get("dt", 0.01)
    options["n_walkers"] = options.get("n_walkers", 50)
    options["n_prop_steps"] = options.get("n_prop_steps", 50)
    options["n_ene_blocks"] = options.get("n_ene_blocks", 50)
    options["n_sr_blocks"] = options.get("n_sr_blocks", 1)
    options["n_blocks"] = options.get("n_blocks", 50)
    options["seed"] = options.get("seed", np.random.randint(1, int(1e6)))
    options["n_eql"] = options.get("n_eql", 1)
    options["ad_mode"] = options.get("ad_mode", None)
    assert options["ad_mode"] in [None, "forward", "reverse", "2rdm"]
    options["orbital_rotation"] = options.get("orbital_rotation", True)
    options["do_sr"] = options.get("do_sr", True)
    options["walker_type"] = options.get("walker_type", "rhf")
    options["symmetry"] = options.get("symmetry", False)
    options["save_walkers"] = options.get("save_walkers", False)
    options["trial"] = options.get("trial", None)
    options["ene0"] = options.get("ene0", 0.0)
    options["free_projection"] = options.get("free_projection", False)
    options["do_grad"] = options.get("do_grad",False)

    # Register checkpointing options
    options["n_steps_per_ckpt"] = options.get("n_steps_per_ckpt", 0)
    options["n_ene_per_ckpt"] = options.get("n_ene_per_ckpt", 0)
    options["do_sr_ckpt"] = options.get("do_sr_ckpt", False)
    options["do_eval_ckpt"] = options.get("do_eval_ckpt", False)

    if abs(ms) != 0:
        try:
            assert options["walker_type"] != "rhf"
            # assert options["trial"] != "rhf"
        except:
            raise ValueError(
                "Open shell systems have to use UHF walkers and non-RHF trials."
            )

    try:
        with h5py.File("observable.h5", "r") as fh5:
            [observable_constant] = fh5["constant"]
            observable_op = np.array(fh5.get("op")).reshape(nmo, nmo)
            if options["walker_type"] == "uhf":
                observable_op = jnp.array([observable_op, observable_op])
            observable = [observable_op, observable_constant]
    except:
        observable = None

    is_ad_mode_enabled = options["ad_mode"] != None
    ham_data = {}
    ham_data["h0"] = h0
    ham_data["chol"] = chol.reshape(nchol, -1)
    ham_data["ene0"] = options["ene0"]
    ham_data["dm0"] = None

    prop_options = {
        key: options[key]
        for key in (
            "dt",
            "n_prop_steps",
            "n_ene_blocks",
            "n_sr_blocks",
            "n_blocks",
            "n_walkers",
            "n_steps_per_ckpt",
            "n_ene_per_ckpt",
            "do_sr_ckpt",
            "do_eval_ckpt",
        )
    }
    prop_options["is_ad_mode_enabled"] = is_ad_mode_enabled

    if options["walker_type"] == "rhf":

        ham_data["h1"] = h1
        if options["symmetry"]:
            ham_data["mask"] = jnp.where(jnp.abs(ham_data["h1"]) > 1.0e-10, 1.0, 0.0)
        else:
            ham_data["mask"] = jnp.ones(ham_data["h1"].shape)
        ham = hamiltonian.hamiltonian(nmo, nelec // 2, nchol)
        prop = propagation.propagator(**prop_options)
        trial = wavefunctions.rhf(norb, nelec // 2)
        wave_data = jnp.array(np.load("rhf.npz")["mo_coeff"]) #jnp.eye(norb)

    elif options["walker_type"] == "uhf":

        ham_data["h1"] = jnp.array([h1, h1])
        if options["symmetry"]:
            ham_data["mask"] = jnp.where(jnp.abs(ham_data["h1"]) > 1.0e-10, 1.0, 0.0)
        else:
            ham_data["mask"] = jnp.ones(ham_data["h1"].shape)

        if options["trial"] == "noci":
            ham = hamiltonian.hamiltonian_noci(nmo, nelec_sp, nchol)

            if options["free_projection"]:
                prop = propagation.propagator_uhf(**{
                    **prop_options,
                    "is_ad_mode_enabled": True,
                    "n_exp_terms": 10,
                })
            else:
                prop = propagation.propagator_uhf(**prop_options)

            with open("dets.pkl", "rb") as f:
                wave_data = pickle.load(f)
            wave_data = [
                jnp.array(wave_data[0]),
                [jnp.array(wave_data[1][0]), jnp.array(wave_data[1][1])],
            ]
            trial = wavefunctions.noci(norb, nelec_sp, wave_data[0].size)

        else:
            ham = hamiltonian.hamiltonian_uhf(nmo, nelec_sp, nchol)

            if options["free_projection"]:
                prop = propagation.propagator_uhf(**{
                    **prop_options,
                    "is_ad_mode_enabled": True,
                    "n_exp_terms": 10,
                })
            else:
                prop = propagation.propagator_uhf(**prop_options)

            trial = wavefunctions.uhf(norb, nelec_sp)
            wave_data = jnp.array(np.load("uhf.npz")["mo_coeff"])

    if rank == 0:
        print(f"# norb: {norb}")
        print(f"# nelec: {nelec_sp}")
        print("#")
        for op in options:
            if options[op] is not None:
                print(f"# {op}: {options[op]}")
        print("#")

    return ham_data, ham, prop, trial, wave_data, observable, options


if __name__ == "__main__":
    ham_data, ham, prop, trial, wave_data, observable, options = _prep_afqmc()
    init = time.time()
    comm.Barrier()
    e_afqmc, err_afqmc = 0.0, 0.0
    if options["free_projection"]:
        driver.fp_afqmc(ham_data, ham, prop, trial, wave_data, observable, options)
    else:
        if(options["do_grad"]):
            os.system(f"rm en_der_afqmc_{comm.rank}.npz")
            print(f"Removed en_der_afqmc_{comm.rank}",flush=True)
            ham_data["dm0"] = np.load("Integral_der.npz")["dm"]
            comm.Barrier()
            e_afqmc, err_afqmc = driver.afqmcGrad(ham_data, ham, prop, trial, wave_data, observable, options)
        else: 
            e_afqmc, err_afqmc = driver.afqmc(ham_data, ham, prop, trial, wave_data, observable, options)
    comm.Barrier()
    end = time.time()
    if rank == 0:
        print(f"ph_afqmc walltime: {end - init}", flush=True)
        np.savetxt("ene_err.txt", np.array([e_afqmc, err_afqmc]))
    comm.Barrier()
